export function hashNameSeed(str: string): number {
  let h = 0;
  for (let i = 0; i < str.length; i++) {
    h = (h * 31 + str.charCodeAt(i)) | 0;
  }
  return Math.abs(h);
}

export function getDefaultAppearance(seedName: string, flagColor = '#dc2626') {
  const h = hashNameSeed(seedName || 'Pirata');
  const builds: BodyBuild[] = ['normal', 'robust', 'slim'];
  const accessories: AccessoryStyle[] = ['none', 'scar', 'glasses', 'eyepatch', 'beard'];
  return {
    race: 'humano' as PirateRace,
    skinTone: SKIN_TONES[h % SKIN_TONES.length].hex,
    hairStyle: HAIR_STYLES[(h >> 1) % HAIR_STYLES.length].id,
    hairColor: HAIR_COLORS[(h >> 2) % HAIR_COLORS.length].hex,
    bodyBuild: builds[(h >> 3) % builds.length],
    outfitStyle: OUTFIT_STYLES[(h >> 4) % OUTFIT_STYLES.length].id,
    outfitColor: flagColor || OUTFIT_COLORS[(h >> 5) % OUTFIT_COLORS.length].hex,
    accessory: accessories[(h >> 6) % accessories.length],
    accessoryColor: undefined as string | undefined,
    hatColor: undefined as string | undefined,
    capeStyle: 'none' as CapeStyle,
    capeColor: undefined as string | undefined,
  };
}

