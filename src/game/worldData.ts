export function getNextCycleColor(currentHex: string | undefined, fallbackHex = '#dc2626'): string {
  const active = (currentHex || fallbackHex).toLowerCase();
  const idx = ITEM_COLOR_CYCLE.findIndex((c) => c.hex.toLowerCase() === active);
  if (idx === -1) return ITEM_COLOR_CYCLE[0].hex;
  return ITEM_COLOR_CYCLE[(idx + 1) % ITEM_COLOR_CYCLE.length].hex;
}

export function getItemColorLabel(hex: string | undefined): string {
  if (!hex) return 'Estándar';
  return ITEM_COLOR_CYCLE.find((c) => c.hex.toLowerCase() === hex.toLowerCase())?.label ?? hex;
}

