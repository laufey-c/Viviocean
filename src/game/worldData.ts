export function getRegionalWeather(
  island: Island,
  day = 1,
  minuteOfDay = 480
): WeatherStatus {
  const block = Math.floor(Math.max(0, minuteOfDay) / 360); // 4 weather windows per day (every 6h in-game)
  const seed = hashNameSeed(`${island.id}_${island.sea}`) + day * 17 + block * 7;

  let pool: WeatherType[];
  if (island.id === 'isla-raijin') {
    pool = ['tormenta', 'tormenta', 'lluvia', 'viento'];
  } else if (island.id === 'isla-drum' || island.id === 'tequila-wolf' || island.id === 'isla-perdida') {
    pool = ['nieve', 'nieve', 'viento', 'lluvia', 'despejado'];
  } else if (island.id === 'thriller-bark' || island.id === 'isla-kuraigana') {
    pool = ['niebla', 'niebla', 'lluvia', 'tormenta'];
  } else if (island.biome === 'desert' || island.id === 'reino-arabasta') {
    pool = ['calor', 'calor', 'despejado', 'viento'];
  } else if (island.biome === 'volcano' || island.biome === 'fire_ice') {
    pool = ['calor', 'tormenta', 'nieve', 'lluvia', 'niebla'];
  } else if (island.sea === 'Mar del Norte') {
    pool = ['nieve', 'viento', 'lluvia', 'niebla', 'despejado'];
  } else if (island.sea === 'Mar del Sur') {
    pool = ['despejado', 'calor', 'viento', 'lluvia'];
  } else if (island.sea === 'Mar del Oeste') {
    pool = ['niebla', 'lluvia', 'despejado', 'viento', 'tormenta'];
  } else if (island.sea === 'Paraíso') {
    pool = ['lluvia', 'tormenta', 'despejado', 'viento', 'niebla'];
  } else if (island.sea === 'Nuevo Mundo') {
    pool = ['tormenta', 'lluvia', 'viento', 'calor', 'despejado', 'niebla'];
  } else {
    // Mar del Este
    pool = ['despejado', 'despejado', 'lluvia', 'viento', 'tormenta'];
  }

  const chosen = pool[seed % pool.length];
  return WEATHER_METADATA[chosen];
}

