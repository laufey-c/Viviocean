export function getIslandSizeTier(island: Island): IslandSizeTier {
  if (island.sizeTier) return island.sizeTier;
  const s = island.scale ?? 1.0;
  if (s >= 2.1) return 'colosal';
  if (s >= 1.65) return 'grande';
  if (s >= 1.2) return 'mediana';
  return 'pequeña';
}

export function getIslandRecommendedDays(island: Island): number {
  if (island.recommendedDays) return island.recommendedDays;
  switch (getIslandSizeTier(island)) {
    case 'colosal':
      return 8;
    case 'grande':
      return 6;
    case 'mediana':
      return 3;
    default:
      return 2;
  }
}

