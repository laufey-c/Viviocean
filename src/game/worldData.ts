export function getShortStageName(fullName: string): string {
  const clean = fullName.trim();
  if (!clean) return 'Jefe';
  if (clean.includes('Big Mom')) return 'Big Mom';
  const mrMatch = clean.match(/^(Mr\.\s*\d+)\b/i);
  if (mrMatch) return mrMatch[1];
  if (/^Sir\s+/i.test(clean)) return clean.replace(/^Sir\s+/i, '').split(' ')[0];
  if (/^Miss\s+/i.test(clean)) return clean.replace(/^Miss\s+/i, '').split(' ')[0];
  if (/^Dr\.\s+/i.test(clean)) return `Dr. ${clean.replace(/^Dr\.\s+/i, '').split(' ')[0]}`;
  if (/^Don\s+/i.test(clean)) return `Don ${clean.replace(/^Don\s+/i, '').split(' ')[0]}`;
  const surnamePrefix = clean.match(
    /^(?:Charlotte|Vinsmoke|Boa|Donquixote|Kurozumi|Nefertari|Saint\s+Figarland|Saint|Monkey\s+D\.|Gol\s+D\.|Marshall\s+D\.|Trafalgar|Eustass|Rob|Bartholomew|Edward|Capone|Basil|X|Scratchmen)\s+(.+)$/i
  );
  if (surnamePrefix && surnamePrefix[1]) {
    return surnamePrefix[1].split(' ')[0];
  }
  return clean.split(' ')[0];
}

